// Builds brand assets from the master logo PNG in docs/brand:
//  - public/brand/mark.svg (vector trace, fill=currentColor)
//  - PWA icons (any + maskable) and favicon PNGs
// Run: pnpm brand:icons
import { readFile, writeFile } from 'node:fs/promises';
import potrace from 'potrace';
import sharp from 'sharp';

const SRC = 'docs/brand/logo-mark-on-light.png';

const svgRaw = await new Promise((res, rej) =>
  potrace.trace(SRC, { threshold: 128, turdSize: 4, optTolerance: 0.2, color: 'currentColor', background: 'transparent' },
    (err, svg) => (err ? rej(err) : res(svg))),
);
const d = svgRaw.match(/ d="([^"]+)"/)[1];

// Tight bounds of the dark pixels
const { data, info } = await sharp(SRC).greyscale().raw().toBuffer({ resolveWithObject: true });
let minX = info.width, minY = info.height, maxX = 0, maxY = 0;
for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
  if (data[y * info.width + x] < 128) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
}
const vb = `${minX} ${minY} ${maxX - minX + 1} ${maxY - minY + 1}`;
const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" fill="currentColor"><path fill-rule="evenodd" d="${d}"/></svg>\n`;
await writeFile('public/brand/mark.svg', mark);
await writeFile('src/ui/brand/mark-path.ts',
  `// Generated by scripts/build-brand-assets.mjs — do not edit.\nexport const MARK_VIEWBOX = '${vb}';\nexport const MARK_PATH = '${d}';\n`);

// Icons: white mark on near-black, square. Maskable gets a larger safe zone.
const icon = async (size, pad, out, bg = '#0B0B0C', fg = '#FFFFFF') => {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <rect width="100%" height="100%" fill="${bg}"/>
  <svg x="${pad}" y="${pad}" width="${size - 2 * pad}" height="${size - 2 * pad}" viewBox="${vb}" color="${fg}" fill="${fg}" preserveAspectRatio="xMidYMid meet"><path fill-rule="evenodd" d="${d}"/></svg></svg>`;
  await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true }).toFile(out);
};
await icon(192, 24, 'public/icons/icon-192.png');
await icon(512, 64, 'public/icons/icon-512.png');
await icon(512, 112, 'public/icons/icon-maskable-512.png');
await icon(180, 24, 'public/icons/apple-touch-icon.png');
await icon(32, 3, 'public/icons/favicon-32.png');
console.log('brand assets built; viewBox', vb, 'path chars', d.length);
